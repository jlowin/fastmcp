"""Vendored snapshot of the IANA URI Scheme registry.

RFC 8252 §7.1 defines a native app's private-use URI scheme as one that is
**not** registered: apps are told to pick a scheme based on a domain name they
control (`com.example.app:`). Deciding whether a redirect URI uses a private-use
scheme therefore means asking whether its scheme is registered -- so this module
vendors the registry itself rather than a hand-picked subset.

That distinction matters for security. Any hand-maintained list (whether it
denylists "dangerous" transports or allowlists "standard" ones) fails *open* for
every scheme nobody thought to include: `coap:`, `stun:`, `turn:`, and `mqtt:`
are all registered network transports that a hand-picked subset is likely to
miss, and each would then be treated as a private-use app scheme and accepted as
a native redirect target. Checking against the actual registry makes the
unanticipated case fail *closed*.

Note that a reverse-domain-looking scheme is **not** a reliable private-use
signal either: `iris.beep`, `z39.50`, and `microsoft.windows.camera` are all
registered despite containing dots. Membership is the only sound test.

Source: https://www.iana.org/assignments/uri-schemes/uri-schemes-1.csv
Includes Permanent, Provisional, and Historical registrations -- all of them are
registered, so none are available for private use.

Snapshot: 423 schemes, retrieved 2026-07-26. Refresh by re-downloading the CSV
above and regenerating this set; IANA additions are infrequent.
"""

